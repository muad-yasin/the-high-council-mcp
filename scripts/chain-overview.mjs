#!/usr/bin/env node
// Writes the README's chain overview (owner, 14 Nov 2026: "A table with Chain, layers, seats, title", one row per seat, the
// flagship at the bottom). Every row is read from chains/<name>.json, so the table cannot drift from the seats a run uses.
// The chains are the ones the Pricing table lists, in the order maintainers/run-costs.json lists them (not by price, so a price change never reorders it); the chain whose personas
// speak in voices (seat_personas.form "voice", the flagship) goes last. `node scripts/chain-overview.mjs` rewrites README.md;
// `--check` exits 1 when the README differs. Pure: reads files, calls nothing, spends nothing.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const DEFAULT_ROOT = join(here, '..');
export const START = '<!-- chains:start (generated by scripts/chain-overview.mjs from the chain files: edit the chains, then run it) -->';
export const END = '<!-- chains:end -->';

const readChain = (root, name) => JSON.parse(readFileSync(join(root, 'chains', `${name}.json`), 'utf8'));
const isFlagship = config => config.seat_personas?.enabled === true && config.seat_personas?.form === 'voice';

/** The chains in table order: as maintainers/run-costs.json lists them, a voiced chain (the flagship) last. */
export function overviewChains(root = DEFAULT_ROOT) {
  const data = JSON.parse(readFileSync(join(root, 'maintainers', 'run-costs.json'), 'utf8'));
  const names = data.groups.flatMap(g => g.chains);
  return [...names.filter(n => !isFlagship(readChain(root, n))), ...names.filter(n => isFlagship(readChain(root, n)))];
}

/** One row per proposer and judge seat: the layer ("Proposer", the judge's layer number, or "Judge" for a judge with none), the title (its persona, or an en dash) and the model id as the chain names it. */
export function seatRows(config) {
  const seats = config.seats || {};
  const row = (layer, s) => ({ layer, title: s.persona || '–', model: s.model });
  const judges = [...(seats.critics || [])].map((s, i) => ({ s, i })).sort((a, b) => (a.s.layer ?? 0) - (b.s.layer ?? 0) || a.i - b.i);
  return [...(seats.proposers || []).map(s => row('Proposer', s)), ...judges.map(({ s }) => row(s.layer ? String(s.layer) : 'Judge', s))];
}

/** The table, markers included. */
export function generateChainOverview(root = DEFAULT_ROOT) {
  const lines = [START, '', '| Chain | Layer | Title | Model |', '|---|---|---|---|'];
  for (const name of overviewChains(root)) {
    seatRows(readChain(root, name)).forEach((r, i) => lines.push(`| ${i === 0 ? `\`${name}\`` : ''} | ${r.layer} | ${r.title} | \`${r.model}\` |`));
  }
  lines.push('', END);
  return lines.join('\n');
}

/** README.md with its chain block replaced by the generated one. Throws when the markers are missing. */
export function readmeWithOverview(root = DEFAULT_ROOT) {
  const text = readFileSync(join(root, 'README.md'), 'utf8');
  const a = text.indexOf(START), b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error('README.md has no chain overview markers');
  return text.slice(0, a) + generateChainOverview(root) + text.slice(b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = readmeWithOverview();
  const have = readFileSync(join(DEFAULT_ROOT, 'README.md'), 'utf8');
  if (process.argv.includes('--check')) { if (want !== have) { console.error('README.md chain overview is stale: run node scripts/chain-overview.mjs'); process.exit(1); } }
  else if (want !== have) { writeFileSync(join(DEFAULT_ROOT, 'README.md'), want); console.log('README.md chain overview rewritten'); }
  else console.log('README.md chain overview is current');
}
